/**
 * Build this product's own landing page, using this product.
 *
 * Driven from a script rather than the chat box only because the chat box now
 * requires a signed-in browser session. It goes through the same generator and
 * the same block model a customer gets, so if the output is bad, that is a real
 * finding about the product rather than an artefact of the script.
 *
 * The fact sheet below is exhaustive on purpose: the generator is instructed
 * never to invent claims, and the surest way to keep it honest is to leave it
 * nothing it needs to invent.
 */
import "dotenv/config";
import { structured } from "../src/lib/llm.ts";
import { BLOCK_REFERENCE } from "../src/lib/blocks.ts";
import { runTool } from "../src/lib/tools.ts";
import { entitlements } from "../src/lib/plan.ts";
import { lintBlocks } from "../src/lib/copyreview.ts";

/**
 * The prompt shown on the finished page.
 *
 * It is this exact string that gets sent, so the page cannot advertise a prompt
 * it was not actually built from. The fact sheet below goes along with it as
 * reference material, and the page says so.
 */
const SEED_PROMPT = `Landing page for Adaptive LP. Explain the mechanism plainly: pages are stored as structured sections instead of HTML, it writes a version of the page per angle, intent decides which angle a visitor sees and statistics choose between versions inside it, traffic splits by Thompson sampling. Highlight the reporting: a funnel in unique people, form starts separate from submits, a click map and an attention map filterable by angle. Free forever, no card, ten free AI messages then bring your own Anthropic key. Lead with the mechanism, no hype, no invented results, one call to action: create a free account.`;

const FACTS = `
WHAT IT IS
Adaptive LP. You describe a landing page in a chat box; it gets built, hosted and
published, then keeps testing itself against real traffic and tells you which
section of the page loses people.

WHO MADE IT AND WHY IT IS FREE
A personal project by Ammar Imtiaz, built to solve a real problem and released
free. It is free forever with no page limit and no card — not a trial, not a
freemium tier with the good parts removed. Serving pages costs nothing per
visitor, so there is nothing to charge for yet. The source is public.

THIS PAGE IS THE PROOF
The landing page you are reading was generated by the software itself, from a
prompt, and is served by it. It is a live page inside the product with its own
variants, funnel and heatmaps — not a static marketing site built separately.
Say this plainly somewhere prominent; it is the strongest thing on the page.

THE PROBLEM IT SOLVES
One page serves many audiences. The ad promises same-day service, the email
promises convenience, the retargeting ad promises a discount — all three land on
one generic page that matches none of them. Building a page per angle is five
pages of work per campaign, so nobody does it.

HOW IT WORKS (all true, all built)
- Pages are stored as structured sections, never HTML. That is what lets one
  page render a version matched to whoever is arriving.
- Name the angles your market argues about and it writes a version of the page
  for each — the promise changes, and the proof and the call to action follow.
- Routing is two layers: intent decides which angle a visitor is allowed to see,
  statistics decide which version of that angle they get. A variant locked to a
  specific ad is also withheld from everyone else, so the optimizer can never
  overrule a promise you actually made.
- Traffic splits by Thompson sampling, not a 50/50 A/B test that never resolves.
  New versions get 100 guaranteed impressions; nothing takes more than 80% of
  traffic, so a decaying winner stays detectable.
- Everything resolves server-side before first paint. No flicker.
- Import an existing page by URL and it rebuilds it as editable sections.
- Publishing is a database flag: live in milliseconds, no deploy per page.
- Your own subdomains work instantly from one wildcard DNS record. Clients can
  point their own domain at it.
- Export any page as one self-contained HTML file; its form still reports back.

WHAT IT MEASURES
- A report per page with a selectable date range and a comparison against the
  previous period.
- A funnel in unique people: landed, read past the first quarter, saw the form,
  clicked a button, started typing, converted. The biggest drop is named.
- Form starts tracked separately from submits — the gap is where forms die.
- Traffic sources credited to a visitor's first view, and device breakdown.
- Two heatmaps: a click map on the real live page, and an attention map shading
  sections by dwell time. Both filterable to one angle, so you can see how
  people arriving on the speed angle read the page differently from people
  arriving on the guarantee angle.
- Leads stored first, then pushed to any CRM webhook and emailed. A broken
  webhook loses nothing.

WHO IT IS FOR
Agencies running paid traffic for several clients; businesses spending real
money on ads with more than one angle; anyone who needs a good landing page in
five minutes and would otherwise not build one.

HONESTY REQUIRED
It is new and no real traffic has run through it yet. Do not claim customers,
results, uptime or a number of pages built. Being straight that it is a new
free project is more credible than pretending otherwise, and it costs nothing
to admit.

ABSOLUTELY DO NOT CLAIM
No conversion-lift percentages. No customer counts, logos, testimonials or
"trusted by". No uptime figures. No prices or plans of any kind — it is free.
No team size, funding, or founding date. No named competitors.
`;

const spec = await structured({
  system: `You write landing pages as structured blocks.

${BLOCK_REFERENCE}

You are writing the landing page for the product described below — the page that
has to make a stranger start a free trial.

Rules for this page specifically:
- Lead with the mechanism, not adjectives. The category is full of tools that
  say "AI-powered optimisation" and explain nothing; the credibility here comes
  from the fact that how it works can be explained in three sentences.
- The only conversion path is signing up. The primary CTA is a link to
  "/sign-up" and its text should reflect that it is free, with no card. Do not
  add a contact form, a demo request, or a calendar.
- Every CTA href is "/sign-up".
- One block must state plainly that this very page was generated by the
  software and is served by it, with its own variants and heatmaps. Put it
  early — it is the proof, not a footnote.
- One block must be honest that the project is new, free, and has no results to
  show yet. Do not bury it.
- No invented facts. The fact sheet is exhaustive; if something is not in it, it
  does not go on the page.
- The footer's body must read exactly: "A project of Ammar Imtiaz" and its
  links array must contain one entry with label "ammarimtiaz.com" and href
  "https://ammarimtiaz.com".
- 7 to 9 blocks. End with a footer.`,
  prompt: `Write the landing page. Return name, goal, and the blocks.\n\nThe prompt you are fulfilling:\n${SEED_PROMPT}\n\nReference material about the product:\n${FACTS}`,
  schema: {
    type: "object",
    additionalProperties: false,
    required: ["name", "goal", "blocksJson"],
    properties: {
      name: { type: "string" },
      goal: { type: "string" },
      blocksJson: { type: "string", description: "The block array, serialised as JSON." },
    },
  },
  maxTokens: 32000,
  accountId: "acct-ammar",
});

const blocks = JSON.parse(spec.blocksJson);
const faultsBefore = lintBlocks(blocks);
if (faultsBefore.length) {
  console.log("Checker found in the first draft:");
  for (const f of faultsBefore) console.log(`  - ${f}`);
  console.log("");
}
const result = await runTool(
  "create_page",
  {
    name: spec.name,
    goal: spec.goal,
    blocks,
    theme: { mode: "dark", accent: "#dfe6ef", bg: "#07090c", surface: "#0f1319", density: "roomy" },
    goal: spec.goal,
  },
  { accountId: "acct-ammar", ents: entitlements("unlimited") },
);

console.log(JSON.stringify({ ...result, name: spec.name, goal: spec.goal }, null, 2));
