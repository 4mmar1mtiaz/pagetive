import "dotenv/config";
import { runTool } from "../src/lib/tools.ts";
import { entitlements } from "../src/lib/plan.ts";
import { lintBlocks } from "../src/lib/copyreview.ts";

const PAGE = "cmt6jqntg0003kbq42akphmcg";
const ctx = { accountId: "acct-ammar", ents: entitlements("unlimited") };

const SEED_PROMPT = `Landing page for Adaptive LP. Explain the mechanism plainly: pages are stored as structured sections instead of HTML, it writes a version of the page per angle, intent decides which angle a visitor sees and statistics choose between versions inside it, traffic splits by Thompson sampling. Highlight the reporting: a funnel in unique people, form starts separate from submits, a click map and an attention map filterable by angle. Free forever, no card, ten free AI messages then bring your own Anthropic key. Lead with the mechanism, no hype, no invented results, one call to action: create a free account.`;

const edits = [
  // The prompt, verbatim. The generator was told to quote it and did not, which
  // is exactly the kind of instruction a second pass is for.
  ["richtext-1", {
    headline: "This page was generated by the software, from this prompt",
    body: `You are reading output. This page was written inside Adaptive LP, stored as sections, and is served live by the product. It is a real page in a real account, with its own angle variants, its own funnel report, its own click map and its own attention map. There is no separate marketing site.

Here is the prompt it was built from, word for word:

"${SEED_PROMPT}"

A fact sheet describing what the product does was supplied alongside it, because the model cannot know features it has never been told. Everything else on this page, the structure, the headlines, the section copy, came out of that prompt in one pass and one editor pass.

Sign up and you can rewrite this very page in a chat box.`,
  }],
  // The conversion path for a product page is an account, not an email capture.
  ["hero-1", { ctaHref: "/sign-up", ctaText: "Create a free account", secondaryCtaText: "See the source", secondaryCtaHref: "https://github.com/ammar1mtiaz/pagetive" }],
  ["cta-1", { ctaHref: "/sign-up", ctaText: "Create a free account" }],
  ["form-1", {
    headline: "Or tell me what you would build first",
    subhead: "Not ready to sign up. Leave this and I will read it.",
    submitText: "Send it",
  }],
];

for (const [blockId, fields] of edits) {
  const r = await runTool("patch_block", { pageId: PAGE, blockId, fields }, ctx);
  console.log(`${blockId}: ${r.error ?? "updated"}`);
}

const page = await runTool("get_page", { pageId: PAGE }, ctx);
const faults = lintBlocks(page.blocks);
console.log(`\nchecker: ${faults.length ? faults.join(" | ") : "no faults"}`);
process.exit(0);
